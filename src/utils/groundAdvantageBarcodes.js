/**
 * Converts control picture Unicode characters (U+2400 to U+241F, and U+21E5 for tab)
 * back to their corresponding ASCII control characters.
 */
export const convertControlPictures = (str) => {
  if (!str) return str;
  return str.replace(/[\u2400-\u241f\u21e5]/g, (char) => {
    const code = char.charCodeAt(0);
    if (code >= 0x2400 && code <= 0x241f) {
      return String.fromCharCode(code - 0x2400);
    }
    if (char === '⇥') {
      return '\t';
    }
    return char;
  });
};
